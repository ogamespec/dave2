#!/usr/bin/env python3
"""Generate src/dd2_uitiles.h from the original image.

Two things live in the same module (segment 0x121C, image 0x121C0):

  * the UI tile bank -- 8x8 cells, 1 byte per row, 4 planes of 13232 bytes.
    Segments DS:0x9EA6/0x9EA8/0x9EAA/0x9EAC are set at 0x0885/0x088B/0x0894/
    0x089A to 0x1881 + p*plane; 0x915A (the 8x8 UI blit) and 0x91F8 (the
    death-sprite blit) both read their pixels from there.
  * the death-sprite records -- 41 entries of 16 bytes at image 0x12200
    (module[8]>>4 = 4 paragraphs past 0x121C).  Entry fields used by 0x91F8:
        +0 bytes per row, +2 rows, +4 offset (added to [0x320C] = module[0x2A]).
    The pixel data therefore starts at plane offset 0x100 + entry[+4].
"""
import struct
import sys

IMAGE = "/mnt/c/Games/DD2/re/ref/orig/DAVE2_IMAGE.bin"
OUT = "/mnt/c/Games/DD2/port/src/dd2_uitiles.h"
MODULE = 0x121C0
PLANE_BASES = (0x18810, 0x1BBC0, 0x1EF70, 0x22320)   # from the segment arithmetic
PLANE_SIZE = 13232                                    # module[0] = 0x33B0
NDEATH = 41
DEATH_REC = 0x12200


def main():
    d = open(IMAGE, "rb").read()
    assert struct.unpack_from("<H", d, MODULE)[0] == PLANE_SIZE
    assert struct.unpack_from("<H", d, MODULE + 0x28)[0] == NDEATH
    out = []
    out.append("/* UI tile bank + death sprites, extracted verbatim from the original")
    out.append("   DAVE2_IMAGE.bin module at segment 0x121C (image 0x121C0).")
    out.append("   Plane segments DS:0x9EA6/0x9EA8/0x9EAA/0x9EAC (0x0885/0x088B/0x0894/")
    out.append("   0x089A) are 0x1881 + p*%d (module[0]), so the four planes" % PLANE_SIZE)
    out.append("   live at image 0x%05X/0x%05X/0x%05X/0x%05X." % PLANE_BASES)
    out.append("   0x915A (UI 8x8 blit) and 0x91F8 (death sprites) both read here.")
    out.append("   Generated by tools/mkuibank.py -- do not edit. */")
    out.append("#ifndef DD2_UITILES_H")
    out.append("#define DD2_UITILES_H")
    out.append("#define DD2_UITILES_N %d   /* 8x8 cells per plane */" % (PLANE_SIZE // 8))
    out.append("static const unsigned char dd2_uitiles[4][%d] = {" % PLANE_SIZE)
    for p in range(4):
        out.append("  {")
        base = PLANE_BASES[p]
        for i in range(0, PLANE_SIZE, 16):
            out.append("    " + ",".join("0x%02x" % v for v in d[base + i:base + i + 16]) + ",")
        out.append("  },")
    out.append("};")
    out.append("")
    out.append("/* Death-sprite records (0x91F8): bytes per row, rows, plane offset. */")
    out.append("#define DD2_NDEATH %d" % NDEATH)
    out.append("static const struct { unsigned short w, h, off; } dd2_death[%d] = {" % NDEATH)
    for i in range(NDEATH):
        b = d[DEATH_REC + i * 16:DEATH_REC + i * 16 + 16]
        w, h, off = struct.unpack_from("<HHH", b, 0)
        name = b[8:16].rstrip(b"\0").decode("latin1")
        out.append("  { %d, %d, 0x%04x },   /* %s */" % (w, h, off, name))
    out.append("};")
    out.append("#endif")
    open(OUT, "w").write("\n".join(out) + "\n")
    print("wrote %s (%d planes x %d bytes, %d death records)"
          % (OUT, 4, PLANE_SIZE, NDEATH))


if __name__ == "__main__":
    sys.exit(main())
