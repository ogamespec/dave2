/* mkicon -- extract one game sprite (default 0x43, the level marker drawn by
   0x13A5) through the port's own loader and write:
     - <out>.rgba   : native w*h RGBA8888, row-major (for the .ico generator)
     - src/dd2_icon.h : a 32x32 RGBA8888 array for SDL_SetWindowIcon
   The sprite data is decoded exactly as the game does (0x9E3 sprite chunks,
   0x7D4 asset setup); nothing here is hand-drawn. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "dd2.h"

void LOGF(const char *fmt, ...) { (void)fmt; }

int main(int argc, char **argv)
{
    static dd2_assets A;
    int idx = argc > 1 ? (int)strtol(argv[1], NULL, 0) : 0x43;
    const char *out = argc > 2 ? argv[2] : "icon/dd2";
    const dd2_sprite *s;
    FILE *f;
    int x, y;

    if (!dd2_load_assets(&A, "/mnt/c/Games/DD2", "")) {
        fprintf(stderr, "mkicon: cannot load assets\n");
        return 1;
    }
    if (idx < 0 || idx >= A.nsprites) { fprintf(stderr, "mkicon: bad index\n"); return 1; }
    s = &A.sprites[idx];
    printf("sprite %d (%s) %dx%d origin (%d,%d)\n", idx, s->name, s->w, s->h,
           s->ox, s->oy);

    /* EGA palette as the game programs it (0x8A3A..); 0 is transparent here. */
    static const unsigned char pal[16][3] = {
        {  0,  0,  0}, {  0,  0,170}, {  0,170,  0}, {  0,170,170},
        {170,  0,  0}, {170,  0,170}, {170, 85,  0}, {170,170,170},
        { 85, 85, 85}, { 85, 85,255}, { 85,255, 85}, { 85,255,255},
        {255, 85, 85}, {255, 85,255}, {255,255, 85}, {255,255,255}
    };

    {   /* native-size RGBA dump */
        char path[512];
        snprintf(path, sizeof path, "%s.rgba", out);
        f = fopen(path, "wb");
        if (!f) { perror(path); return 1; }
        fputc(s->w & 0xff, f); fputc((s->w >> 8) & 0xff, f);
        fputc(s->h & 0xff, f); fputc((s->h >> 8) & 0xff, f);
        for (y = 0; y < s->h; y++)
            for (x = 0; x < s->w; x++) {
                int on = s->mask && s->mask[y * s->w + x];
                int c  = s->px ? (s->px[y * s->w + x] & 15) : 0;
                fputc(pal[c][0], f); fputc(pal[c][1], f);
                fputc(pal[c][2], f); fputc(on ? 255 : 0, f);
            }
        fclose(f);
        printf("wrote %s\n", path);
    }

    {   /* 32x32 header for the window icon (nearest 2x of the 16x16 art) */
        FILE *h = fopen("src/dd2_icon.h", "w");
        int ox, oy;
        if (!h) { perror("src/dd2_icon.h"); return 1; }
        fprintf(h, "/* Application icon: game sprite %d (\"%s\"), the level marker\n"
                   "   drawn by 0x13A5.  Generated by tools/mkicon.c -- do not edit. */\n",
                idx, s->name);
        fprintf(h, "#ifndef DD2_ICON_H\n#define DD2_ICON_H\n");
        fprintf(h, "#define DD2_ICON_W 32\n#define DD2_ICON_H_ 32\n");
        fprintf(h, "static const unsigned char dd2_icon_rgba[32*32*4] = {\n");
        for (oy = 0; oy < 32; oy++) {
            fprintf(h, "  ");
            for (ox = 0; ox < 32; ox++) {
                int sx = ox / 2, sy = oy / 2, on, c;
                if (sx >= s->w) sx = s->w - 1;
                if (sy >= s->h) sy = s->h - 1;
                on = s->mask && s->mask[sy * s->w + sx];
                c  = s->px ? (s->px[sy * s->w + sx] & 15) : 0;
                fprintf(h, "%3d,%3d,%3d,%3d,", pal[c][0], pal[c][1], pal[c][2],
                        on ? 255 : 0);
            }
            fprintf(h, "\n");
        }
        fprintf(h, "};\n#endif\n");
        fclose(h);
        printf("wrote src/dd2_icon.h\n");
    }
    return 0;
}
